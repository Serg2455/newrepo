# The main entry point to the application.
# @private
# @param [Args] args - DragonRuby arguments
# @return [void]
def init args
    default(args)
end

# Defines setting defaults.
# @private
# @param [Args] args - DragonRuby arguments
# @return [void]
def default args
    # All defaults
    default_time(args)
    default_map(args)
    default_dwarves(args)
    default_camera(args)
    default_gui(args)
    default_task_manager(args)
end

# Called once per frame.
# @param [Args] args - DragonRuby arguments
# @return [void]
def tick args
    # Initializes the game on startup (when tick_count == 0)
    init(args) if args.tick_count == 0

    update(args) # Updates the game loop
    draw(args) # Renders the game
end

# Updates the game loop.
# @private
# @param [Args] args - DragonRuby arguments
# @return [void]
def update args
    # All updates
    update_reset(args)
    update_time(args)
    update_camera(args)
    update_game(args)
    update_gui(args)
    update_reorder(args)
end

# Renders the game.
# @private
# @param [Args] args - DragonRuby arguments
# @return [void]
def draw args
    # All renders
    clear_screen(args)
    render_game(args)
    render_gui(args)
end
